import type { Language, Unit } from './types'

export function isDecimalUnit(unit: Unit): boolean {
  return (
    unit === 'kg' ||
    unit === 'g' ||
    unit === 'm' ||
    unit === 'cm' ||
    unit === 'ml' ||
    unit === 'L'
  )
}

export function qtyStep(unit: Unit): number {
  if (unit === 'kg' || unit === 'm' || unit === 'L') return 0.5
  if (unit === 'g' || unit === 'cm' || unit === 'ml') return 10
  return 1
}

